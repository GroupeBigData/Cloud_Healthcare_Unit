-- Gold - DDL dim_patient : un patient pseudonymisé (identifiant HMAC, sexe, année de naissance).
CREATE TABLE IF NOT EXISTS chu.gold.dim_patient (
  patient_sk       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL
                   COMMENT 'Clé de substitution ; -1 = patient inconnu',
  patient_id       STRING NOT NULL COMMENT 'Identifiant pseudonymisé (HMAC-SHA256), clé naturelle',
  sexe             STRING NOT NULL COMMENT 'M, F ou INCONNU',
  annee_naissance  INT             COMMENT 'Année de naissance (date complète supprimée en local)',
  CONSTRAINT pk_dim_patient PRIMARY KEY (patient_sk)
) COMMENT 'Gold - dimension patient, pseudonymisée et généralisée (k-anonymat k = 182)';