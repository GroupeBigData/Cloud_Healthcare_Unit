-- Gold - DDL dim_etablissement : une structure de santé, région intégrée (modèle en étoile).
CREATE TABLE IF NOT EXISTS chu.gold.dim_etablissement (
  etablissement_sk          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL
                            COMMENT 'Clé de substitution ; -1 = établissement inconnu',
  identifiant_organisation  STRING  NOT NULL COMMENT 'Clé naturelle : lettre de type + identifiant',
  type_structure            STRING  NOT NULL COMMENT 'F, C ou R',
  libelle_type              STRING  NOT NULL COMMENT 'Libellé du type de structure',
  finess_geo                STRING           COMMENT 'FINESS géographique (structures F)',
  finess_juridique          STRING           COMMENT 'FINESS de l''entité juridique',
  est_entite_juridique      BOOLEAN NOT NULL COMMENT 'Vrai si la fiche décrit l''entité juridique elle-même',
  raison_sociale            STRING           COMMENT 'Raison sociale du site',
  code_commune              STRING           COMMENT 'Code commune INSEE',
  commune                   STRING           COMMENT 'Libellé de la commune',
  code_departement          STRING           COMMENT 'Code département',
  code_region               STRING           COMMENT 'Code de la zone (dénormalisé depuis dim_region)',
  libelle_region            STRING           COMMENT 'Libellé de la zone (dénormalisé depuis dim_region)',
  CONSTRAINT pk_dim_etablissement PRIMARY KEY (etablissement_sk)
) COMMENT 'Gold - dimension établissement (référentiel des structures de santé)';