-- Gold - DDL dim_professionnel : un professionnel de santé, spécialité intégrée (modèle en étoile).
CREATE TABLE IF NOT EXISTS chu.gold.dim_professionnel (
  professionnel_sk           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL
                             COMMENT 'Clé de substitution ; -1 = professionnel inconnu',
  type_identifiant           STRING NOT NULL COMMENT 'ADELI ou RPPS',
  identifiant                STRING NOT NULL COMMENT 'ADELI 9 chiffres ou RPPS 11 chiffres ; clé naturelle avec le type',
  categorie_professionnelle  STRING          COMMENT 'Catégorie professionnelle',
  profession                 STRING          COMMENT 'Profession',
  code_specialite            STRING          COMMENT 'Code de la spécialité',
  fonction                   STRING          COMMENT 'Fonction associée à la spécialité',
  specialite                 STRING          COMMENT 'Libellé de la spécialité (NULL si inconnue)',
  CONSTRAINT pk_dim_professionnel PRIMARY KEY (professionnel_sk)
) COMMENT 'Gold - dimension professionnel de santé (table source tronquée à 1 048 575 lignes)';