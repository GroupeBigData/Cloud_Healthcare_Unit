-- Gold - DDL dim_region : 18 régions INSEE, zones COM et ETR, membre inconnu.
CREATE TABLE IF NOT EXISTS chu.gold.dim_region (
  region_sk       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL
                  COMMENT 'Clé de substitution ; -1 = région inconnue',
  code_region     STRING NOT NULL COMMENT 'Code région INSEE (découpage 2016), COM ou ETR',
  libelle_region  STRING NOT NULL COMMENT 'Libellé officiel INSEE ou libellé de la zone',
  type_zone       STRING NOT NULL COMMENT 'region | hors_region | etranger | inconnu',
  CONSTRAINT pk_dim_region PRIMARY KEY (region_sk)
) COMMENT 'Gold - dimension région (COG INSEE 2026 + zones hors région)';