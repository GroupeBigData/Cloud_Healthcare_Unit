-- Gold - DDL dim_diagnostic : un code diagnostic et son libellé.
CREATE TABLE IF NOT EXISTS chu.gold.dim_diagnostic (
  diagnostic_sk  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL
                 COMMENT 'Clé de substitution ; -1 = diagnostic inconnu',
  code_diag      STRING NOT NULL COMMENT 'Code diagnostic (format CIM-10), clé naturelle',
  libelle        STRING          COMMENT 'Libellé du diagnostic',
  lettre_cim10   STRING          COMMENT 'Première lettre du code : regroupement approximatif des chapitres CIM-10',
  CONSTRAINT pk_dim_diagnostic PRIMARY KEY (diagnostic_sk)
) COMMENT 'Gold - dimension diagnostic';