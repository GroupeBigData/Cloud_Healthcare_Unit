-- Gold - DDL dim_enquete : les enquêtes de satisfaction e-Satis de la HAS.
CREATE TABLE IF NOT EXISTS chu.gold.dim_enquete (
  enquete_sk    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL
                COMMENT 'Clé de substitution ; -1 = enquête inconnue',
  code_enquete  STRING NOT NULL COMMENT '48H_MCO ou CA_MCO',
  libelle       STRING NOT NULL COMMENT 'Libellé de l''enquête',
  perimetre     STRING          COMMENT 'Patients interrogés',
  CONSTRAINT pk_dim_enquete PRIMARY KEY (enquete_sk)
) COMMENT 'Gold - dimension enquête e-Satis ; les scores de deux enquêtes ne se comparent pas';